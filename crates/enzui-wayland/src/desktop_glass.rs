/// The most regions one surface may carry.
pub const MAX_REGIONS: usize = 32;
/// Floats per region on the wire.
pub const REGION_FLOATS: usize = 25;

/// One glass region: a rounded rectangle in surface-local logical pixels, the
/// 16 material tokens in `MaterialTokens` field order, and the sRGB tint.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GlassRegion {
    /// Left edge.
    pub x: f32,
    /// Top edge.
    pub y: f32,
    /// Width.
    pub width: f32,
    /// Height.
    pub height: f32,
    /// Corner radius.
    pub radius: f32,
    /// `blur_sigma` through `protected_inset`, in `MaterialTokens` order.
    pub tokens: [f32; 16],
    /// Red, green, blue and alpha, sRGB-encoded.
    pub tint: [f32; 4],
}

/// The most cutouts one surface may carry.
pub const MAX_CUTOUTS: usize = 32;

/// A rounded rectangle, in surface-local logical pixels, where the surface
/// draws opaque content over its glass: the compositor neither filters nor
/// paints the glass there (`set_cutouts`, version 3).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GlassCutout {
    /// Left edge.
    pub x: f32,
    /// Top edge.
    pub y: f32,
    /// Width.
    pub width: f32,
    /// Height.
    pub height: f32,
    /// Corner radius; the corners outside it still show glass.
    pub radius: f32,
}

/// The `set_cutouts` payload for `cutouts`: the first [`MAX_CUTOUTS`], with
/// sizes clamped to zero and non-finite values zeroed, as for regions.
#[must_use]
pub fn encode_cutouts(cutouts: &[GlassCutout]) -> Vec<u8> {
    cutouts
        .iter()
        .take(MAX_CUTOUTS)
        .flat_map(|cutout| {
            [
                cutout.x,
                cutout.y,
                cutout.width.max(0.0),
                cutout.height.max(0.0),
                cutout.radius.max(0.0),
            ]
        })
        .map(|value| if value.is_finite() { value } else { 0.0 })
        .flat_map(f32::to_le_bytes)
        .collect()
}

/// The soft shadow the compositor draws outside every region.
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub struct GlassShadow {
    /// Gaussian reach, logical pixels.
    pub blur: f32,
    /// Downward offset, logical pixels.
    pub offset_y: f32,
    /// Black at this opacity next to the edge; zero draws none.
    pub opacity: f32,
}

/// The `set_regions` payload for `regions`: the first [`MAX_REGIONS`], sizes
/// clamped to zero and non-finite values zeroed, since either is a protocol
/// error that would disconnect the app.
#[must_use]
pub fn encode_regions(regions: &[GlassRegion]) -> Vec<u8> {
    regions
        .iter()
        .take(MAX_REGIONS)
        .flat_map(|region| {
            let mut floats = [0.0; REGION_FLOATS];
            floats[..5].copy_from_slice(&[
                region.x,
                region.y,
                region.width.max(0.0),
                region.height.max(0.0),
                region.radius.max(0.0),
            ]);
            floats[5..21].copy_from_slice(&region.tokens);
            floats[21..].copy_from_slice(&region.tint);
            floats
        })
        .map(|value| if value.is_finite() { value } else { 0.0 })
        .flat_map(f32::to_le_bytes)
        .collect()
}

/// Why a window cannot have compositor glass.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DesktopGlassError {
    /// Not a Wayland window, or the payload was not the window's objects.
    NotWayland,
    /// The compositor offers no `enzui_material_manager_v1`.
    Unsupported,
    /// The window's surface is gone.
    WindowGone,
    /// The connection dropped, or the compositor did not answer in time.
    Disconnected,
}

impl core::fmt::Display for DesktopGlassError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(match self {
            Self::NotWayland => "not a Wayland window",
            Self::Unsupported => "the compositor does not paint glass (enzui_material_manager_v1)",
            Self::WindowGone => "the window surface is gone",
            Self::Disconnected => "the compositor did not answer",
        })
    }
}

impl std::error::Error for DesktopGlassError {}

/// The compositor glass of one window. Cheap to clone; the glass is removed
/// when the last clone drops.
#[derive(Clone)]
pub struct DesktopGlass(Arc<Inner>);

struct Inner {
    connection: Connection,
    manager: EnzuiMaterialManagerV1,
    surface: WlSurface,
    sent: Mutex<Sent>,
    backdrop: Arc<Backdrop>,
}

#[derive(Default)]
struct Sent {
    object: Option<EnzuiSurfaceMaterialV1>,
    regions: Vec<u8>,
    shadow: GlassShadow,
    /// The mode last sent to `object`.
    measure_only: bool,
    /// The mode asked for, kept while no object exists yet so the object is
    /// made in it.
    want_measure_only: bool,
    /// The cutouts last sent to `object`, and those asked for, kept while no
    /// object exists yet.
    cutouts: Vec<u8>,
    want_cutouts: Vec<u8>,
}

type Waker = Box<dyn Fn() + Send + Sync>;

// What the compositor measured behind each region, from its luminance events.
#[derive(Default)]
struct Backdrop {
    luminance: Mutex<Vec<Option<f32>>>,
    wakers: Mutex<Vec<Waker>>,
}

impl ObjectData for Backdrop {
    fn event(
        self: Arc<Self>,
        _: &Backend,
        message: Message<ObjectId, OwnedFd>,
    ) -> Option<Arc<dyn ObjectData>> {
        if let [Argument::Uint(region), Argument::Fixed(value)] = message.args.as_slice()
            && let Ok(region) = usize::try_from(*region)
            && region < MAX_REGIONS
        {
            if let Ok(mut luminance) = self.luminance.lock() {
                if luminance.len() <= region {
                    luminance.resize(region + 1, None);
                }
                luminance[region] = Some((*value as f32 / 256.0).clamp(0.0, 1.0));
            }
            if let Ok(wakers) = self.wakers.lock() {
                wakers.iter().for_each(|wake| wake());
            }
        }
        None
    }

    fn destroyed(&self, _: ObjectId) {}
}

impl DesktopGlass {
    /// Find the compositor's glass for `surface` on its own `connection`.
    ///
    /// The first window on a connection makes one registry round trip, waiting
    /// at most `timeout`; later windows reuse what it found. Run it off the
    /// draw path, e.g. in the task that resolves the window's objects.
    ///
    /// A surface has one glass: binding it again while an earlier binding
    /// lives returns that binding (as [`Clone`] would), since the protocol
    /// allows one material object per surface.
    ///
    /// # Errors
    ///
    /// [`DesktopGlassError::Unsupported`] when the compositor paints no glass;
    /// the others when the window or connection is gone.
    pub fn bind(
        connection: &Connection,
        surface: &WlSurface,
        timeout: Duration,
    ) -> Result<Self, DesktopGlassError> {
        if !surface.is_alive() {
            return Err(DesktopGlassError::WindowGone);
        }
        let manager = shared_manager(connection, timeout)?;
        /// Each bound surface and its live owner.
        type Bound = Vec<(ObjectId, Weak<Inner>)>;
        static BOUND: OnceLock<Mutex<Bound>> = OnceLock::new();
        let mut bound = BOUND
            .get_or_init(Mutex::default)
            .lock()
            .map_err(|_| DesktopGlassError::Disconnected)?;
        bound.retain(|(_, inner)| inner.strong_count() > 0);
        if let Some(inner) = bound
            .iter()
            .find(|(id, _)| *id == surface.id())
            .and_then(|(_, inner)| inner.upgrade())
        {
            return Ok(Self(inner));
        }
        let inner = Arc::new(Inner {
            connection: connection.clone(),
            manager,
            surface: surface.clone(),
            sent: Mutex::new(Sent::default()),
            backdrop: Arc::new(Backdrop::default()),
        });
        bound.push((surface.id(), Arc::downgrade(&inner)));
        Ok(Self(inner))
    }

    /// [`Self::bind`] from the `(Connection, WlSurface, u64)` payload
    /// `iced::window::wayland_parent_export` resolves to.
    ///
    /// # Errors
    ///
    /// [`DesktopGlassError::NotWayland`] for a missing or foreign payload, or
    /// any error of [`Self::bind`].
    pub fn from_payload(
        payload: Option<Box<dyn Any + Send>>,
        timeout: Duration,
    ) -> Result<Self, DesktopGlassError> {
        let (connection, surface, _) = *payload
            .ok_or(DesktopGlassError::NotWayland)?
            .downcast::<crate::WaylandParentPayload>()
            .map_err(|_| DesktopGlassError::NotWayland)?;
        Self::bind(&connection, &surface, timeout)
    }

    /// Replace the glass regions and their shadow, applied on the window's
    /// next commit. Sends nothing when neither changed; an empty slice removes
    /// the glass. False when nothing could be sent.
    pub fn set_regions(&self, regions: &[GlassRegion], shadow: GlassShadow) -> bool {
        let bytes = encode_regions(regions);
        let Ok(mut sent) = self.0.sent.lock() else {
            return false;
        };
        if !self.0.surface.is_alive() || !self.0.manager.is_alive() {
            return false;
        }
        if sent.regions == bytes && (sent.shadow == shadow || bytes.is_empty()) {
            return true;
        }
        if sent.object.is_none() {
            if bytes.is_empty() {
                return true;
            }
            sent.object = self
                .0
                .manager
                .send_constructor(
                    enzui_material_manager_v1::Request::GetSurfaceMaterial {
                        surface: self.0.surface.clone(),
                    },
                    Arc::<Backdrop>::clone(&self.0.backdrop),
                )
                .ok();
            // A mode and cutouts asked for before the object existed apply
            // from the object's first commit.
            if let Some(object) = sent.object.as_ref()
                && sent.want_measure_only
                && self.measures()
            {
                object.set_measure_only(1);
                sent.measure_only = true;
            }
            if let Some(object) = sent.object.clone()
                && !sent.want_cutouts.is_empty()
                && self.cuts()
            {
                object.set_cutouts(sent.want_cutouts.clone());
                let Sent {
                    cutouts,
                    want_cutouts,
                    ..
                } = &mut *sent;
                cutouts.clone_from(want_cutouts);
            }
        }
        let Some(object) = sent.object.clone() else {
            return false;
        };
        if sent.shadow != shadow {
            object.set_shadow(
                f64::from(shadow.blur),
                f64::from(shadow.offset_y),
                f64::from(shadow.opacity),
            );
            sent.shadow = shadow;
        }
        // Region indices name different panes once the count changes.
        if sent.regions.len() != bytes.len()
            && let Ok(mut luminance) = self.0.backdrop.luminance.lock()
        {
            luminance.clear();
        }
        object.set_regions(bytes.clone());
        sent.regions = bytes;
        self.0.connection.flush().is_ok()
    }

    /// Remove the glass on the next commit.
    pub fn clear(&self) {
        self.set_regions(&[], GlassShadow::default());
    }

    /// Measure the backdrop without painting, applied on the next commit, so
    /// glass whose ink follows its backdrop appears already in that ink.
    /// Asked before the first [`Self::set_regions`], it applies when the glass
    /// is made. Ignored by a compositor that does not measure.
    pub fn set_measure_only(&self, measure_only: bool) {
        let Ok(mut sent) = self.0.sent.lock() else {
            return;
        };
        sent.want_measure_only = measure_only;
        if sent.measure_only == measure_only || !self.measures() {
            return;
        }
        if let Some(object) = sent.object.as_ref().filter(|object| object.is_alive()) {
            object.set_measure_only(u32::from(measure_only));
            sent.measure_only = measure_only;
            let _ = self.0.connection.flush();
        }
    }

    /// Replace the cutouts, applied on the window's next commit: where the
    /// window covers its glass with opaque content, so the compositor spends
    /// nothing on glass there. Sends nothing when unchanged; asked before the
    /// first [`Self::set_regions`], they apply when the glass is made.
    /// Ignored by a compositor older than version 3, which paints the glass
    /// under them, unseen.
    pub fn set_cutouts(&self, cutouts: &[GlassCutout]) {
        let bytes = encode_cutouts(cutouts);
        let Ok(mut sent) = self.0.sent.lock() else {
            return;
        };
        sent.want_cutouts.clone_from(&bytes);
        if sent.cutouts == bytes || !self.cuts() {
            return;
        }
        if let Some(object) = sent.object.clone().filter(Proxy::is_alive) {
            object.set_cutouts(bytes.clone());
            sent.cutouts = bytes;
            let _ = self.0.connection.flush();
        }
    }

    /// Whether the compositor takes cutouts (version 3).
    #[must_use]
    pub fn cuts(&self) -> bool {
        self.0.manager.is_alive() && self.0.manager.version() >= 3
    }

    /// Whether the compositor reports the backdrop's brightness.
    #[must_use]
    pub fn measures(&self) -> bool {
        self.0.manager.is_alive() && self.0.manager.version() >= 2
    }

    /// The brightness, `0` to `1` sRGB-encoded, the compositor last measured
    /// behind region `index` of the last [`Self::set_regions`], a frame or two
    /// ago; `None` before it has.
    #[must_use]
    pub fn luminance(&self, index: usize) -> Option<f32> {
        self.0
            .backdrop
            .luminance
            .lock()
            .ok()?
            .get(index)
            .copied()
            .flatten()
    }

    /// Call `wake` whenever a new measurement arrives, from the thread that
    /// reads the compositor's events: a window that is otherwise still can
    /// redraw to follow it.
    pub fn on_luminance(&self, wake: impl Fn() + Send + Sync + 'static) {
        if let Ok(mut wakers) = self.0.backdrop.wakers.lock() {
            wakers.push(Box::new(wake));
        }
    }
}

// Two handles are equal when they are the glass of the same window.
impl PartialEq for DesktopGlass {
    fn eq(&self, other: &Self) -> bool {
        self.0.surface == other.0.surface
    }
}

impl Eq for DesktopGlass {}

impl std::hash::Hash for DesktopGlass {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.0.surface.id().hash(state);
    }
}

impl core::fmt::Debug for DesktopGlass {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("DesktopGlass")
            .field("surface", &self.0.surface.id())
            .field("measures", &self.measures())
            .finish_non_exhaustive()
    }
}

impl Drop for Inner {
    fn drop(&mut self) {
        if let Ok(sent) = self.sent.get_mut()
            && let Some(object) = sent.object.take()
            && object.is_alive()
        {
            object.destroy();
            let _ = self.connection.flush();
        }
    }
}

// One manager per connection: a process usually has one, and binding again per
// window would leak a global and an event thread each time.
fn shared_manager(
    connection: &Connection,
    timeout: Duration,
) -> Result<EnzuiMaterialManagerV1, DesktopGlassError> {
    // The weak marker dies with the connection's event thread.
    type Known = (Weak<()>, Connection, EnzuiMaterialManagerV1);
    static SHARED: OnceLock<Mutex<Vec<Known>>> = OnceLock::new();
    let shared = SHARED.get_or_init(Mutex::default);
    let mut shared = shared.lock().map_err(|_| DesktopGlassError::Disconnected)?;
    shared.retain(|(alive, _, manager)| alive.strong_count() > 0 && manager.is_alive());
    if let Some((_, _, manager)) = shared
        .iter()
        .find(|(_, known, _)| known.backend() == connection.backend())
    {
        return Ok(manager.clone());
    }
    let (manager, queue) = discover(connection, timeout)?;
    let alive = Arc::new(());
    shared.push((Arc::downgrade(&alive), connection.clone(), manager.clone()));
    // The manager's events arrive on this queue, which nothing else
    // dispatches: a thread dispatches it for as long as the connection lives
    // (the glass objects handle their measurements as they are read). It
    // never reads the socket. The connection is the window's, and its event
    // loop reads it, routing each event to the queue that owns its object and
    // waking this thread for ours. A second reader would take the event
    // loop's own events (its frame callbacks among them) off the socket
    // without waking it, stalling the window's next frame until some other
    // event arrived.
    let mut queue = queue;
    std::thread::Builder::new()
        .name("enzui-glass-events".into())
        .spawn(move || {
            let _alive = alive;
            let mut globals = Globals::default();
            let waker = std::task::Waker::from(Arc::new(Unpark(std::thread::current())));
            let mut context = std::task::Context::from_waker(&waker);
            while queue
                .poll_dispatch_pending(&mut context, &mut globals)
                .is_pending()
            {
                std::thread::park();
            }
        })
        .map_err(|_| DesktopGlassError::Disconnected)?;
    Ok(manager)
}

/// Wakes the glass events thread when its queue receives events.
struct Unpark(std::thread::Thread);

impl std::task::Wake for Unpark {
    fn wake(self: Arc<Self>) {
        self.0.unpark();
    }
}

fn discover(
    connection: &Connection,
    timeout: Duration,
) -> Result<(EnzuiMaterialManagerV1, EventQueue<Globals>), DesktopGlassError> {
    let (discovered, globals) =
        registry::discover(connection, timeout).map_err(|_| DesktopGlassError::Disconnected)?;
    let manager = globals.bind::<EnzuiMaterialManagerV1>(&discovered, 3);
    let queue = discovered.finish();
    Ok((manager.ok_or(DesktopGlassError::Unsupported)?, queue))
}

