//! Liquid glass the compositor paints behind a window (`enzui-material-v1`).
//!
//! In-app glass can only sample what the app itself drew. A panel that should
//! show the desktop behind its window (the wallpaper, other windows) asks the
//! compositor instead: the window stays transparent there, and the compositor
//! filters what lies below with the same tokens the framework would use.
//!
//! [`DesktopGlass::bind`] finds the `enzui_material_manager_v1` global on the
//! window's own connection, or reports [`DesktopGlassError::Unsupported`] so
//! the caller keeps its in-app glass. [`DesktopGlass::set_regions`] sends the
//! regions; like every surface state it applies on the window's next commit,
//! so it must be sent while the frame is drawn, before it is presented.

