//! An in-process `wayland-server` compositor wired to one client over a
//! `socketpair(2)`. It offers `wl_compositor` and, as asked, the
//! `enzui-material-v1` and `xdg_system_bell_v1` globals, and records what it
//! is sent. It renders nothing.

