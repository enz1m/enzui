/// What the compositor saw, in arrival order.
#[derive(Debug, Clone, PartialEq)]
pub enum Seen {
    Regions(Vec<u8>),
    Shadow(f64, f64, f64),
    MeasureOnly(u32),
    Cutouts(Vec<u8>),
    Commit,
    Destroyed,
    /// The bell rang, for the surface with this protocol id or none.
    Bell(Option<u32>),
    /// A hint object was made for a surface.
    Object(&'static str),
    /// `wp_content_type_v1.set_content_type`.
    ContentType(u32),
    /// `wp_tearing_control_v1.set_presentation_hint`.
    Tearing(u32),
}

#[derive(Default)]
pub struct Witness {
    pub seen: Vec<Seen>,
    material: Option<EnzuiSurfaceMaterialV1>,
}

pub struct Comp(Arc<Mutex<Witness>>);

impl GlobalDispatch<WlCompositor, ()> for Comp {
    fn bind(
        _: &mut Self,
        _: &DisplayHandle,
        _: &Client,
        resource: New<WlCompositor>,
        (): &(),
        data_init: &mut DataInit<'_, Self>,
    ) {
        data_init.init(resource, ());
    }
}

impl Dispatch<WlCompositor, ()> for Comp {
    fn request(
        _: &mut Self,
        _: &Client,
        _: &WlCompositor,
        request: wl_compositor::Request,
        (): &(),
        _: &DisplayHandle,
        data_init: &mut DataInit<'_, Self>,
    ) {
        if let wl_compositor::Request::CreateSurface { id } = request {
            data_init.init(id, ());
        }
    }
}

impl Dispatch<WlSurface, ()> for Comp {
    fn request(
        state: &mut Self,
        _: &Client,
        _: &WlSurface,
        request: wl_surface::Request,
        (): &(),
        _: &DisplayHandle,
        _: &mut DataInit<'_, Self>,
    ) {
        if let wl_surface::Request::Commit = request {
            state.0.lock().unwrap().seen.push(Seen::Commit);
        }
    }
}

impl GlobalDispatch<EnzuiMaterialManagerV1, ()> for Comp {
    fn bind(
        _: &mut Self,
        _: &DisplayHandle,
        _: &Client,
        resource: New<EnzuiMaterialManagerV1>,
        (): &(),
        data_init: &mut DataInit<'_, Self>,
    ) {
        data_init.init(resource, ());
    }
}

impl Dispatch<EnzuiMaterialManagerV1, ()> for Comp {
    fn request(
        state: &mut Self,
        _: &Client,
        _: &EnzuiMaterialManagerV1,
        request: enzui_material_manager_v1::Request,
        (): &(),
        _: &DisplayHandle,
        data_init: &mut DataInit<'_, Self>,
    ) {
        if let enzui_material_manager_v1::Request::GetSurfaceMaterial { id, .. } = request {
            let material = data_init.init(id, ());
            let mut witness = state.0.lock().unwrap();
            witness.material = Some(material);
            witness.seen.push(Seen::Object("material"));
        }
    }
}

impl Dispatch<EnzuiSurfaceMaterialV1, ()> for Comp {
    fn request(
        state: &mut Self,
        _: &Client,
        _: &EnzuiSurfaceMaterialV1,
        request: enzui_surface_material_v1::Request,
        (): &(),
        _: &DisplayHandle,
        _: &mut DataInit<'_, Self>,
    ) {
        let seen = match request {
            enzui_surface_material_v1::Request::SetRegions { regions } => Seen::Regions(regions),
            enzui_surface_material_v1::Request::SetShadow {
                blur,
                offset_y,
                opacity,
            } => Seen::Shadow(blur, offset_y, opacity),
            enzui_surface_material_v1::Request::SetMeasureOnly { measure_only } => {
                Seen::MeasureOnly(measure_only)
            }
            enzui_surface_material_v1::Request::SetCutouts { cutouts } => Seen::Cutouts(cutouts),
            enzui_surface_material_v1::Request::Destroy => Seen::Destroyed,
        };
        state.0.lock().unwrap().seen.push(seen);
    }
}

impl GlobalDispatch<XdgSystemBellV1, ()> for Comp {
    fn bind(
        _: &mut Self,
        _: &DisplayHandle,
        _: &Client,
        resource: New<XdgSystemBellV1>,
        (): &(),
        data_init: &mut DataInit<'_, Self>,
    ) {
        data_init.init(resource, ());
    }
}

impl Dispatch<XdgSystemBellV1, ()> for Comp {
    fn request(
        state: &mut Self,
        _: &Client,
        _: &XdgSystemBellV1,
        request: xdg_system_bell_v1::Request,
        (): &(),
        _: &DisplayHandle,
        _: &mut DataInit<'_, Self>,
    ) {
        if let xdg_system_bell_v1::Request::Ring { surface } = request {
            let surface =
                surface.map(|surface| wayland_server::Resource::id(&surface).protocol_id());
            state.0.lock().unwrap().seen.push(Seen::Bell(surface));
        }
    }
}

pub struct ClientId;
impl wayland_server::backend::ClientData for ClientId {}

pub struct Server {
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}

impl Drop for Server {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

/// The optional globals a fixture compositor offers.
#[derive(Debug, Clone, Copy, Default)]
pub struct Offer {
    /// `enzui_material_manager_v1` at this version.
    pub material: Option<u32>,
    /// `xdg_system_bell_v1`.
    pub bell: bool,
    /// Content type and tearing control.
    pub hints: bool,
}

/// A compositor offering `wl_compositor` and the globals in `offer`.
pub fn compositor(offer: Offer) -> (CConnection, Arc<Mutex<Witness>>, Server) {
    let witness = Arc::new(Mutex::new(Witness::default()));
    let mut display: Display<Comp> = Display::new().expect("server display");
    let mut handle = display.handle();
    handle.create_global::<Comp, WlCompositor, ()>(4, ());
    if let Some(version) = offer.material {
        handle.create_global::<Comp, EnzuiMaterialManagerV1, ()>(version, ());
    }
    if offer.bell {
        handle.create_global::<Comp, XdgSystemBellV1, ()>(1, ());
    }
    if offer.hints {
        use wayland_protocols::wp::content_type::v1::server::wp_content_type_manager_v1::WpContentTypeManagerV1;
        use wayland_protocols::wp::tearing_control::v1::server::wp_tearing_control_manager_v1::WpTearingControlManagerV1;
        handle.create_global::<Comp, WpContentTypeManagerV1, ()>(1, ());
        handle.create_global::<Comp, WpTearingControlManagerV1, ()>(1, ());
    }
    let (server_side, client_side) = UnixStream::pair().expect("socketpair");
    handle
        .insert_client(server_side, Arc::new(ClientId))
        .expect("insert client");
    let connection = CConnection::from_socket(client_side).expect("client connection");
    let mut comp = Comp(Arc::clone(&witness));
    let stop = Arc::new(AtomicBool::new(false));
    let stopping = Arc::clone(&stop);
    let thread = thread::spawn(move || {
        while !stopping.load(Ordering::SeqCst) {
            if display.dispatch_clients(&mut comp).is_err() || display.flush_clients().is_err() {
                break;
            }
            thread::sleep(Duration::from_millis(1));
        }
    });
    (
        connection,
        witness,
        Server {
            stop,
            thread: Some(thread),
        },
    )
}

#[derive(Default)]
struct ClientState {
    compositor: Option<CWlCompositor>,
}

impl CDispatch<CWlRegistry, ()> for ClientState {
    fn event(
        state: &mut Self,
        registry: &CWlRegistry,
        event: c_registry::Event,
        (): &(),
        _: &CConnection,
        qh: &CQueueHandle<Self>,
    ) {
        if let c_registry::Event::Global {
            name, interface, ..
        } = event
            && interface == CWlCompositor::interface().name
        {
            state.compositor = Some(registry.bind(name, 4, qh, ()));
        }
    }
}

impl CDispatch<CWlCompositor, ()> for ClientState {
    fn event(
        _: &mut Self,
        _: &CWlCompositor,
        _: <CWlCompositor as CProxy>::Event,
        (): &(),
        _: &CConnection,
        _: &CQueueHandle<Self>,
    ) {
    }
}

impl CDispatch<CWlSurface, ()> for ClientState {
    fn event(
        _: &mut Self,
        _: &CWlSurface,
        _: <CWlSurface as CProxy>::Event,
        (): &(),
        _: &CConnection,
        _: &CQueueHandle<Self>,
    ) {
    }
}

pub fn window(connection: &CConnection) -> CWlSurface {
    let mut queue = connection.new_event_queue::<ClientState>();
    let qh = queue.handle();
    let mut state = ClientState::default();
    let _registry = connection.display().get_registry(&qh, ());
    queue.roundtrip(&mut state).expect("globals");
    let surface = state
        .compositor
        .clone()
        .expect("wl_compositor")
        .create_surface(&qh, ());
    queue.roundtrip(&mut state).expect("surface");
    surface
}

pub const TIMEOUT: Duration = Duration::from_secs(5);

/// Has the compositor report brightness `value` (`0..=1`) behind `region`
/// of the glass it made.
pub fn send_luminance(witness: &Mutex<Witness>, region: u32, value: f64) {
    witness
        .lock()
        .unwrap()
        .material
        .as_ref()
        .expect("the glass was made")
        .luminance(region, value);
}

/// Waits until the compositor has seen `count` messages, then returns them.
pub fn seen(witness: &Mutex<Witness>, count: usize) -> Vec<Seen> {
    let deadline = Instant::now() + TIMEOUT;
    loop {
        let seen = witness.lock().unwrap().seen.clone();
        if seen.len() >= count || Instant::now() >= deadline {
            return seen;
        }
        thread::sleep(Duration::from_millis(2));
    }
}
