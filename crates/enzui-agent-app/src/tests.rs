/// Service directories under a fresh scratch directory: `user` and `system`.
struct ServiceDirs {
    root: std::path::PathBuf,
}

impl ServiceDirs {
    fn new(tag: &str) -> Self {
        let root = std::env::temp_dir().join(format!(
            "enzui-agent-app-activation-{}-{tag}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&root);
        for dir in ["user", "system"] {
            std::fs::create_dir_all(root.join(dir)).unwrap();
        }
        Self { root }
    }

    fn dirs(&self) -> Vec<std::path::PathBuf> {
        vec![self.root.join("user"), self.root.join("system")]
    }

    fn write(&self, dir: &str, name: &str, exec: &std::path::Path) {
        std::fs::write(
            self.root.join(dir).join("io.github.enzui.Fixture.service"),
            format!(
                "# Generated by enzui-agent; do not edit.\n[D-BUS Service]\nName={name}\nExec={} --agent-background\nSystemdService=enzui-agent-{name}.service\n",
                exec.display()
            ),
        )
        .unwrap();
    }
}

impl Drop for ServiceDirs {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.root);
    }
}

const FIXTURE_ID: &str = "io.github.enzui.Fixture";

#[test]
fn only_the_installed_executable_converges_through_activation() {
    let exe = std::env::current_exe().unwrap();
    let other = std::path::Path::new("/usr/bin/env");

    let none = ServiceDirs::new("none");
    assert!(
        !installed_activation_in(&none.dirs(), FIXTURE_ID, &exe),
        "no service file: a development run stays independent"
    );

    let ours = ServiceDirs::new("ours");
    ours.write("system", FIXTURE_ID, &exe);
    assert!(installed_activation_in(&ours.dirs(), FIXTURE_ID, &exe));

    let theirs = ServiceDirs::new("theirs");
    theirs.write("system", FIXTURE_ID, other);
    assert!(
        !installed_activation_in(&theirs.dirs(), FIXTURE_ID, &exe),
        "an installed copy elsewhere does not capture this build"
    );

    let renamed = ServiceDirs::new("renamed");
    renamed.write("system", "io.github.enzui.Other", &exe);
    assert!(!installed_activation_in(&renamed.dirs(), FIXTURE_ID, &exe));

    let shadowed = ServiceDirs::new("shadowed");
    shadowed.write("user", FIXTURE_ID, other);
    shadowed.write("system", FIXTURE_ID, &exe);
    assert!(
        !installed_activation_in(&shadowed.dirs(), FIXTURE_ID, &exe),
        "the bus uses the first service file for a name"
    );
}

#[test]
fn a_service_exec_names_its_program_through_shell_quoting() {
    for (exec, program) in [
        ("/usr/bin/app --gapplication-service", Some("/usr/bin/app")),
        (
            "\"/opt/My App/bin/app\" --service",
            Some("/opt/My App/bin/app"),
        ),
        ("'/opt/My App/app' x", Some("/opt/My App/app")),
        ("/opt/My\\ App/app", Some("/opt/My App/app")),
        ("\"/opt/a\\\"b\"", Some("/opt/a\"b")),
        ("\"/opt/unterminated", None),
        ("   ", None),
    ] {
        assert_eq!(super::first_argument(exec).as_deref(), program, "{exec}");
    }
}

/// A connector that stopped for good does not cut short the app's own work:
/// the worker exits once that work is done.
#[test]
fn a_stopped_connector_lets_the_apps_work_finish_first() {
    use enzui_agent::center::{AppFunctionRegistry, ConnectorEvent};
    let mut host = CenterHost::<()>::offline(
        AppFunctionRegistry::from_functions(Vec::new()).expect("empty registry"),
    );
    let _ = host.receive_with_ends(ConnectorEvent::Stopped {
        reason: "credential revoked".into(),
    });
    let process = AgentProcess::<()>::desktop(None);
    assert_eq!(
        disposition(Some(&host), &process, true),
        Disposition::Working
    );
    assert_eq!(disposition(Some(&host), &process, false), Disposition::Exit);
}
